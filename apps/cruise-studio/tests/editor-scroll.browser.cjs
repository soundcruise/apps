const test=require('node:test');
const assert=require('node:assert/strict');
const {chromium,webkit}=require('playwright');
const origin='http://127.0.0.1:18874';

for(const engine of ['chrome','webkit'])test('score scrolling and both audio shortcuts in '+engine,async()=>{
    const browser=await (engine==='chrome'?chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'}):webkit.launch());
    const p=await browser.newPage({viewport:{width:1440,height:730}});
    p.setDefaultTimeout(6500);
    const errors=[];p.on('pageerror',e=>errors.push(e.message));
    try{
        const {viewerFixture}=await import('./helpers/viewer-fixture.mjs'),f=viewerFixture();
        await p.goto(origin);await p.click('#open-sheet-cruise');
        await p.locator('#sc-import-json').setInputFiles({name:'scroll.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(f.score))});
        await p.waitForFunction(id=>CruiseStudio.sheetCruise.getSession()?.draft.projectId===id,f.score.projectId);
        const project=()=>p.evaluate(()=>CruiseStudio.sheetCruise.getSession().workingSnapshot());
        const before=await project();
        await p.click('#sc-playback-settings');
        await p.getByRole('dialog').getByRole('button',{name:'自動スクロール設定'}).click();
        const panel=p.getByRole('dialog',{name:'譜面の自動スクロール設定'});
        await panel.getByLabel('スクロールの動き').selectOption('viewport');
        const tempo=panel.getByLabel('演奏とスクロールのBPM');
        await tempo.fill('180');await tempo.press('Tab');
        assert.equal(await p.locator('#sc-practice-tempo').inputValue(),'180');
        const position=()=>p.evaluate(()=>CruiseStudio.scroll.getRoot('sheetCruise').scrollTop);
        const start=await p.evaluate(()=>{const root=CruiseStudio.scroll.getRoot('sheetCruise');root.scrollTop=(root.scrollHeight-root.clientHeight)/2;return root.scrollTop;});
        assert(start>50);
        const play=panel.getByRole('button',{name:'▶ 再生',exact:true}),stop=panel.getByRole('button',{name:'■ 停止'});
        await play.click();await p.waitForFunction(()=>document.querySelector('#sc-slot-overlay').dataset.playbackBar==='1');
        assert(Math.abs(await position()-start)<25);
        await p.waitForFunction(y=>CruiseStudio.scroll.getRoot('sheetCruise').scrollTop>y+12,start);
        await p.evaluate(()=>CruiseStudio.scroll.getRoot('sheetCruise').dispatchEvent(new WheelEvent('wheel')));
        const held=await position();await p.waitForTimeout(250);assert.equal(await position(),held);
        await panel.getByRole('button',{name:'スクロール再開'}).click();
        await p.waitForFunction(y=>CruiseStudio.scroll.getRoot('sheetCruise').scrollTop>y+8,held);
        await panel.locator('[data-auto-scroll]').uncheck();const fixed=await position();
        await p.waitForTimeout(300);assert.equal(await position(),fixed);await stop.click();
        await panel.locator('[data-auto-scroll]').check();await panel.getByLabel('スクロールの動き').selectOption('score');
        await panel.getByLabel('演奏位置の表示').selectOption('center');
        await panel.getByRole('button',{name:'閉じる'}).click();
        await p.locator('#sc-sheet-scale-box .sheet-bar[data-bar-number="8"]').click({position:{x:4,y:4}});
        const middle=await position();
        await p.click('#sc-playback-settings');
        await p.getByRole('dialog').getByRole('button',{name:'自動スクロール設定'}).click();
        await panel.getByLabel('演奏位置の表示').selectOption('start');assert(await position()>middle+8);
        await panel.getByLabel('演奏位置の表示').selectOption('end');assert(await position()<middle-8);
        await panel.getByLabel('演奏位置の表示').selectOption('center');
        await panel.getByRole('button',{name:'カスタム'}).click();
        await panel.locator('[data-native-scroll-speed]').fill('20');
        await panel.getByRole('button',{name:'閉じる'}).click();
        assert.deepEqual(await project(),before);
        await p.locator('#sc-menu-scroll-settings').evaluate(e=>e.closest('details').open=true);
        await p.click('#sc-menu-scroll-settings');
        assert.equal(await panel.getByLabel('演奏位置の表示').inputValue(),'center');
        assert.equal(await panel.getByRole('button',{name:'カスタム'}).getAttribute('aria-pressed'),'true');
        await panel.getByRole('button',{name:'閉じる'}).click();
        await p.goto(origin+'/apps/score-viewer/local/');
        await p.waitForFunction(()=>!!window.CruiseViewer);
        const file=await f.contract.codec.encode(f.score,f.metadata);
        assert(await p.evaluate(text=>CruiseViewer.view.openBytes(text),file.text));
        await p.click('[data-viewer-action=playback-settings]');
        await p.getByRole('dialog').getByRole('button',{name:'自動スクロール設定'}).click();
        await panel.waitFor();
        const gaps=await p.locator('.sv-toolbar>.sv-zoom:visible').evaluate(z=>{
            const box=z.getBoundingClientRect(),button=z.firstElementChild.getBoundingClientRect();
            return [button.top-box.top,box.bottom-button.bottom];
        });
        assert.deepEqual(gaps,[4,4]);assert.deepEqual(errors,[]);
    }finally{await browser.close();}
});
