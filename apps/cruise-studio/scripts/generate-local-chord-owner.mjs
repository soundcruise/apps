// Build-time reuse of the actual owner UI. No eval, network or production entry changes.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const studio=new URL('../',import.meta.url),chord=new URL('../chord-cruise/',studio);
export const output=new URL('.local-chord-owner.mjs',import.meta.url);
export function renderOwnerBundle(){
    const names=['core/storage.js','ui/focus-trap.js','ui/fretboard.js','ui/chord-builder.js','ui/explore.js'];
    const sources=names.map(name=>{
        let source=fs.readFileSync(new URL('js/'+name,chord),'utf8');
        if(name==='ui/explore.js'){
            const anchor='setScaleType: setScaleType';
            if(source.split(anchor).length!==2)throw Error('Owner explore export changed; review local integration');
            source=source.replace(anchor,anchor+',\n        readSelectedChord: selectedChord, readCurrentForm: currentForm,\n        readFingerLabel: function(finger){ return FINGER_LABELS[finger] || ""; }, readMarkerRole: roleForChordInterval');
        }
        return '// Original owner: '+name+'\n'+source;
    });
    const css=fs.readFileSync(new URL('theme.css',chord),'utf8');
    const transfer=fs.readFileSync(new URL('js/modules/sheet-cruise/chord-name-transfer.mjs',studio),'utf8').replace(/^export /gm,'');
    const forms=fs.readFileSync(new URL('js/modules/sheet-cruise/chord-form-transfer.mjs',studio),'utf8').replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
    const exporter=fs.readFileSync(new URL('scripts/chord-name-exporter.mjs',studio),'utf8').replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
    const bookmarklet='javascript:'+encodeURIComponent('(()=>{'+transfer+'\n'+forms+'\n'+exporter+'\ntry{installChordNameExporter();}catch(e){alert(e.message);}})()');
    return '// GENERATED by generate-local-chord-owner.mjs. Excluded from public packages.\n'+
        'export const ownerCSS='+JSON.stringify(css)+';\n'+
        'export const exportBookmarklet='+JSON.stringify(bookmarklet)+';\n'+
        'export function createOwnerUI(window,document){\n'+sources.join('\n')+'\nreturn window.ChordCruise;\n}\n';
}
export function ensureOwnerBundle(){const source=renderOwnerBundle();if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==source)fs.writeFileSync(output,source);}
if(process.argv[1]===fileURLToPath(import.meta.url))ensureOwnerBundle();
